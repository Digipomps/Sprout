#!/usr/bin/env python3
"""Embed the reviewed coordinator in the single-file Sprout executable."""
import argparse, base64, hashlib, pathlib, sys
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
source = root / 'Packages/SproutCore/Sources/SproutCore/Resources/sprout-service.py'
target = source.parent.parent / 'ScaffoldServiceProgram.swift'
raw = source.read_bytes()
encoded = base64.b64encode(raw).decode('ascii')
lines = '\n'.join(encoded[i:i+100] for i in range(0, len(encoded), 100))
expected = '// Generated by Scripts/embed_scaffold_service.py; do not edit.\nimport Foundation\n\nenum ScaffoldServiceProgram {\n    static let sha256 = "' + hashlib.sha256(raw).hexdigest() + '"\n    static var data: Data { Data(base64Encoded: """\n' + lines + '\n""", options: .ignoreUnknownCharacters)! }\n}\n'
if args.check:
    if not target.exists() or target.read_text() != expected:
        sys.exit('Embedded coordinator is stale; run Scripts/embed_scaffold_service.py')
    print('Embedded coordinator matches source SHA256 ' + hashlib.sha256(raw).hexdigest())
else:
    target.write_text(expected)
    print('Embedded coordinator generated')
